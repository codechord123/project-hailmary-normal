/**
 * 자료(그림) 문제용 가벼운 아이콘.
 * figure 설명의 키워드로 대표 이모지를 골라, 실제 삽화 전까지 시각적 힌트를 준다.
 */
const MAP: [RegExp, string][] = [
  [/저작권|창작물|베끼|글을 베/, '💻'],
  [/점자/, '🦯'],
  [/어린이 보호|스쿨존|보호 구역/, '🚸'],
  [/저상버스|버스/, '🚌'],
  [/주차/, '🅿️'],
  [/소방|화재/, '🚒'],
  [/교통|신호|횡단/, '🚦'],
  [/환경|생태|자연/, '🌳'],
  [/급식|먹거리|식품/, '🍱'],
  [/선거|투표/, '🗳️'],
  [/재판|법정|판사/, '⚖️'],
]

export function figureIcon(figure: string): string {
  for (const [re, e] of MAP) if (re.test(figure)) return e
  return '🖼️'
}
